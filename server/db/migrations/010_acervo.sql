CREATE TABLE categorias (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  CONSTRAINT categorias_nome_unico UNIQUE (nome)
);

CREATE TABLE artistas (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome            text NOT NULL,
  nacionalidade   text,
  ano_nascimento  integer,
  ano_falecimento integer,
  biografia       text,
  foto_url        text,
  CONSTRAINT artistas_anos_validos CHECK (
    ano_falecimento IS NULL OR ano_nascimento IS NULL OR ano_falecimento >= ano_nascimento
  )
);

CREATE TABLE obras (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo       text NOT NULL,
  artista_id   integer NOT NULL REFERENCES artistas (id) ON DELETE RESTRICT,
  categoria_id integer NOT NULL REFERENCES categorias (id) ON DELETE RESTRICT,
  ano          integer NOT NULL,
  tecnica      text NOT NULL,
  dimensoes    text,
  descricao    text NOT NULL,
  imagem_url   text NOT NULL,
  em_exibicao  boolean NOT NULL DEFAULT false,
  criado_em    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT obras_titulo_tamanho CHECK (char_length(titulo) BETWEEN 1 AND 150),
  CONSTRAINT obras_ano_valido CHECK (ano > 0),
  CONSTRAINT obras_descricao_tamanho CHECK (char_length(descricao) BETWEEN 20 AND 2000),
  CONSTRAINT obras_imagem_url_valida CHECK (
    imagem_url LIKE '/assets/img/%' OR imagem_url LIKE 'https://%'
  )
);
