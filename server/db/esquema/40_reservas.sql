-- Esquema da área reservas (responsável: M6).

CREATE TABLE reservas (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo      text NOT NULL,
  usuario_id  integer NOT NULL REFERENCES usuarios (id),
  evento_id   integer REFERENCES eventos (id),
  data_visita date NOT NULL,
  qtd_inteira integer NOT NULL DEFAULT 0,
  qtd_meia    integer NOT NULL DEFAULT 0,
  valor_total numeric(10, 2) NOT NULL,
  status      text NOT NULL DEFAULT 'confirmada',
  criado_em   timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT reservas_codigo_unico UNIQUE (codigo),
  CONSTRAINT reservas_status_valido
    CHECK (status IN ('confirmada', 'cancelada')),
  CONSTRAINT reservas_quantidades_validas
    CHECK (qtd_inteira >= 0 AND qtd_meia >= 0),
  CONSTRAINT reservas_total_valido
    CHECK (qtd_inteira + qtd_meia BETWEEN 1 AND 10),
  CONSTRAINT reservas_valor_valido
    CHECK (valor_total >= 0)
);

CREATE INDEX reservas_usuario_idx
  ON reservas (usuario_id);

CREATE INDEX reservas_evento_confirmadas_idx
  ON reservas (evento_id)
  WHERE status = 'confirmada';
