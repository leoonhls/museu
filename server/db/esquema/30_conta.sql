CREATE TABLE usuarios (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       text NOT NULL,
  email      text NOT NULL,
  senha_hash text NOT NULL,
  papel      text NOT NULL DEFAULT 'visitante',
  -- Preferências da página de perfil (Entrega 2); o service completa os campos que faltarem.
  perfil     jsonb NOT NULL DEFAULT '{}',
  criado_em  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE favoritos (
  usuario_id integer NOT NULL REFERENCES usuarios (id),
  obra_id    integer NOT NULL REFERENCES obras (id),
  criado_em  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, obra_id)
);

-- Histórico de ações da conta (cadastro, login, perfil, favoritos), mostrado no perfil (M7).
-- Apagar um usuário apaga junto o histórico dele.
CREATE TABLE historico_conta (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  tipo       text NOT NULL,
  descricao  text NOT NULL,
  data_hora  timestamptz NOT NULL DEFAULT now()
);
